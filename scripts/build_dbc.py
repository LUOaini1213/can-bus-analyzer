"""Rebuild dbc/toyota_nodsu_pt_generated.dbc from the vendored opendbc sources.

opendbc does not commit its *_generated.dbc files; they are produced at build
time by opendbc/dbc/generator/generator.py, which simply concatenates the
files named in `CM_ "IMPORT ...";` lines in front of the template.  This
script re-implements that concatenation (same header/separator comments) so
the vendored generated file can be reproduced byte-for-byte from the three
upstream files in dbc/upstream/.

Usage:  python scripts/build_dbc.py          # (re)write the generated file
        python scripts/build_dbc.py --check  # exit 1 if it would change
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "dbc" / "upstream"
TEMPLATE = "toyota_nodsu_pt.dbc"
OUT = ROOT / "dbc" / "toyota_nodsu_pt_generated.dbc"
INCLUDE = re.compile(r'CM_ "IMPORT (.*?)";\n')


def _read(name: str) -> str:
    return (UPSTREAM / name).read_bytes().decode("utf-8")


def build() -> str:
    template = _read(TEMPLATE)
    parts = ['CM_ "AUTOGENERATED FILE, DO NOT EDIT";\n']
    for inc in INCLUDE.findall(template):
        parts.append(f'\n\nCM_ "Imported file {inc} starts here";\n')
        parts.append(_read(inc))
    parts.append(f'\nCM_ "{TEMPLATE} starts here";\n')
    parts.append(INCLUDE.sub("", template))
    return "".join(parts)


def main() -> int:
    content = build().encode("utf-8")
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_bytes() == content
        print("generated DBC up to date" if ok else "generated DBC differs from upstream concat")
        return 0 if ok else 1
    OUT.write_bytes(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
